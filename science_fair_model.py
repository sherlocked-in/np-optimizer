def clean_score(size, charge, rmt, amt, tox, cost):
    design = np.array([[size/200, charge, rmt, amt, tox/5, cost/6]])
    bbb = model.predict(design)[0]
    total = bbb - (tox/5)*0.3 - (cost/6)*0.2 - abs(size/100-0.8)*0.1
    return total, bbb

