def create_sensitivity_plot(model, params):
    """Parameter sensitivity analysis"""
    fig, axes = plt.subplots(2, 3, figsize=(15, 10))
    axes = axes.flatten()
    
    param_names = ['Size', 'PEG', 'Ligand Density', 'Hydrophobicity', 'Stiffness']
    param_indices = [0, 4, 5, 8, 9]  # Correct parameter indices
    
    for i, (name, ax, idx) in enumerate(zip(param_names, axes[:5], param_indices)):
        values = np.linspace(10 if idx == 0 else 1, 200 if idx == 0 else 5, 50)
        scores = [model.calculate_score(params[:idx] + [v] + params[idx+1:])['bbb'] for v in values]
        
        ax.plot(values, scores, linewidth=3, color='navy')
        ax.axvline(params[idx], color='red', linestyle='--', alpha=0.8, linewidth=2, label=f'Current: {params[idx]:.1f}')
        ax.set_title(f'{name} Sensitivity', fontweight='bold', fontsize=12)
        ax.set_xlabel(name)
        ax.set_ylabel('BBB Score')
        ax.grid(True, alpha=0.3)
        ax.legend()
    
    axes[5].axis('off')
    plt.suptitle('Global Sensitivity Analysis (All Other Parameters Fixed)', fontsize=16, fontweight='bold')
    plt.tight_layout()
    return fig

